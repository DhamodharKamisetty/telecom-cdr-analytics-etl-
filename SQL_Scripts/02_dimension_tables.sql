-- Step 2: Dimension table creation

CREATE TABLE DIM_TIME (
    TIME_KEY            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_DATE           DATE NOT NULL UNIQUE,
    DAY_NUM             NUMBER(2) NOT NULL,
    MONTH_NUM           NUMBER(2) NOT NULL,
    MONTH_NAME          VARCHAR2(20) NOT NULL,
    QUARTER_NUM         NUMBER(1) NOT NULL,
    YEAR_NUM            NUMBER(4) NOT NULL
);

CREATE TABLE DIM_TOWER (
    TOWER_KEY           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TOWER_ID            VARCHAR2(50) NOT NULL UNIQUE,
    TOWER_NAME          VARCHAR2(100),
    CITY                VARCHAR2(100),
    STATE_NAME          VARCHAR2(100),
    REGION              VARCHAR2(100)
);

CREATE TABLE DIM_CALL_TYPE (
    CALLTYPE_KEY        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CALL_TYPE_CODE      VARCHAR2(30) NOT NULL UNIQUE,
    CALL_TYPE_NAME      VARCHAR2(100) NOT NULL,
    IS_INTERNATIONAL    CHAR(1) DEFAULT 'N' CHECK (IS_INTERNATIONAL IN ('Y', 'N'))
);

CREATE TABLE DIM_CUSTOMER (
    CUSTOMER_KEY        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID         VARCHAR2(50) NOT NULL,
    CUSTOMER_NAME       VARCHAR2(150),
    CUSTOMER_SEGMENT    VARCHAR2(50),
    PLAN_NAME           VARCHAR2(100),
    EFFECTIVE_FROM_DT   DATE NOT NULL,
    EFFECTIVE_TO_DT     DATE NOT NULL,
    IS_CURRENT          CHAR(1) DEFAULT 'Y' CHECK (IS_CURRENT IN ('Y', 'N')),
    CONSTRAINT UQ_DIM_CUSTOMER_SCD2 UNIQUE (CUSTOMER_ID, EFFECTIVE_FROM_DT)
);
